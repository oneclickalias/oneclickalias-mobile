package com.oneclickalias.app.data.session

import java.nio.ByteBuffer
import java.security.GeneralSecurityException
import java.security.ProviderException
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Encrypts the stored session. Implementations throw [GeneralSecurityException] on any failure. */
interface TokenCipher {
    fun encrypt(plaintext: ByteArray): ByteArray

    fun decrypt(blob: ByteArray): ByteArray
}

/** Supplies the AES key; on a device that is [AndroidKeystoreKeySource]. */
interface SecretKeySource {
    /** The existing key, or a newly generated one. */
    fun getOrCreate(): SecretKey

    /** Forgets the key (it is broken or no longer usable). */
    fun delete()
}

/**
 * AES-256-GCM with a random 96-bit IV per encryption, generated by the cipher
 * itself (the Android Keystore refuses caller-chosen IVs). Blob layout:
 * `version (1) | iv length (1) | iv | ciphertext + 128-bit tag`.
 */
class AesGcmTokenCipher(private val keys: SecretKeySource) : TokenCipher {

    override fun encrypt(plaintext: ByteArray): ByteArray = try {
        encryptWith(keys.getOrCreate(), plaintext)
    } catch (e: GeneralSecurityException) {
        retryWithNewKey(plaintext)
    } catch (e: ProviderException) {
        // The Keystore reports some key failures as unchecked ProviderException.
        retryWithNewKey(plaintext)
    }

    override fun decrypt(blob: ByteArray): ByteArray {
        if (blob.size < HEADER_SIZE + IV_SIZE + TAG_SIZE_BYTES || blob[0] != VERSION || blob[1].toInt() != IV_SIZE) {
            throw GeneralSecurityException("unsupported session blob")
        }
        val iv = blob.copyOfRange(HEADER_SIZE, HEADER_SIZE + IV_SIZE)
        return try {
            Cipher.getInstance(TRANSFORMATION).run {
                init(Cipher.DECRYPT_MODE, keys.getOrCreate(), GCMParameterSpec(TAG_SIZE_BITS, iv))
                updateAAD(AAD)
                doFinal(blob, HEADER_SIZE + IV_SIZE, blob.size - HEADER_SIZE - IV_SIZE)
            }
        } catch (e: ProviderException) {
            throw GeneralSecurityException("keystore failure", e)
        }
    }

    // A key that cannot encrypt any more (e.g. Keystore entry damaged) is replaced;
    // data under the old key is lost anyway and gets discarded on the next read.
    private fun retryWithNewKey(plaintext: ByteArray): ByteArray {
        keys.delete()
        return try {
            encryptWith(keys.getOrCreate(), plaintext)
        } catch (e: ProviderException) {
            throw GeneralSecurityException("keystore failure", e)
        }
    }

    private fun encryptWith(key: SecretKey, plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)
        cipher.updateAAD(AAD)
        val ciphertext = cipher.doFinal(plaintext)
        val iv = cipher.iv
        if (iv.size != IV_SIZE) throw GeneralSecurityException("unexpected iv size")
        return ByteBuffer.allocate(HEADER_SIZE + iv.size + ciphertext.size)
            .put(VERSION)
            .put(iv.size.toByte())
            .put(iv)
            .put(ciphertext)
            .array()
    }

    private companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val VERSION: Byte = 1
        const val HEADER_SIZE = 2
        const val IV_SIZE = 12
        const val TAG_SIZE_BITS = 128
        const val TAG_SIZE_BYTES = TAG_SIZE_BITS / 8

        // Binds the ciphertext to its purpose: a blob made for something else fails.
        val AAD = "oneclickalias.session.v1".toByteArray()
    }
}
